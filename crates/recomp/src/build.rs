//! The recompile pipeline build scripts and the CLI share: a ROM in, translated C out, and
//! that C compiled with clang into a static library. Nothing but the ROM decides what is
//! built: any image the loader accepts translates.
//!
//! Generated code needs clang (clang-cl on MSVC targets): cross-function jumps rely on
//! `musttail` for guaranteed tail calls.

use std::{
    env, fs, io,
    path::{Path, PathBuf},
};

use anygenesis_analysis::{Analysis, FlagLiveness, LivenessOptions, Origin, analyze};
use anygenesis_codegen_c::{CheckPoints, EmitOptions, Output, emit};
use anygenesis_rom::{Rom, RomError};
use anygenesis_shared::c_marker_line;

/// The second line of every generated file, after the ROM marker.
const GENERATED: &str = "/* Generated by AnyGenesis. Do not edit. */";

/// Why the pipeline stopped.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum BuildError {
    #[error("loading the ROM {}: {source}", path.display())]
    Rom { path: PathBuf, source: RomError },
    #[error("writing {}: {source}", path.display())]
    Write { path: PathBuf, source: io::Error },
    #[error("translated C needs clang or clang-cl, found {}", path.display())]
    NotClang { path: PathBuf },
    #[error("compiling {library}: {source}")]
    Compile { library: String, source: cc::Error },
    #[error("a game program needs stepped code, and the translation has none")]
    NotStepped,
}

/// An analysed game and its translation.
#[derive(Debug)]
pub struct Translation {
    pub analysis: Analysis,
    pub output: Output,
}

/// Loads the ROM image at `path`.
///
/// # Errors
/// Returns [`BuildError::Rom`] for a missing or malformed image.
pub fn load_rom(path: &Path) -> Result<Rom, BuildError> {
    Rom::load(path).map_err(|source| BuildError::Rom {
        path: path.to_owned(),
        source,
    })
}

/// The options a game executable is built with: cycle accounting, a check point at the start
/// of every block, and stepped code for every kept ROM address, which the check points'
/// slow paths run (native everywhere). Interrupts then arrive at the instruction boundary
/// the interpreter takes them at, and no address in ROM lacks native code.
pub fn game_options() -> EmitOptions {
    EmitOptions {
        cycles: true,
        check_points: CheckPoints::BlockStarts,
        stepped: true,
        ..EmitOptions::default()
    }
}

/// The flag liveness a game executable is built with: every check point reads the whole
/// status register, so the frame an interrupt pushes there holds exact flags.
pub fn game_liveness() -> LivenessOptions {
    LivenessOptions {
        check_points_read_sr: true,
    }
}

/// Emits C for every function of `analysis`, with the flags `liveness` proves dead pruned;
/// `rom` is the image `analysis` came from.
pub fn emit_program(
    analysis: &Analysis,
    rom: &Rom,
    liveness: LivenessOptions,
    options: &EmitOptions,
) -> Output {
    let liveness = FlagLiveness::new(analysis, liveness);
    emit(analysis, &liveness, options, rom.bytes())
}

/// Analyses `rom` from its vectors and translates it.
pub fn translate(rom: &Rom, liveness: LivenessOptions, options: &EmitOptions) -> Translation {
    translate_analysis(rom, analyze(rom), liveness, options)
}

/// Translates `rom` as `analysis`, made from it, found its code.
pub fn translate_analysis(
    rom: &Rom,
    analysis: Analysis,
    liveness: LivenessOptions,
    options: &EmitOptions,
) -> Translation {
    let output = emit_program(&analysis, rom, liveness, options);
    Translation { analysis, output }
}

/// Returns the entries of the functions reset and the exception vectors start, ascending.
pub fn vector_handlers(analysis: &Analysis) -> Vec<u32> {
    analysis
        .functions
        .values()
        .filter(|function| {
            function
                .origins
                .iter()
                .any(|origin| matches!(origin, Origin::Reset | Origin::Vector(_)))
        })
        .map(|function| function.entry.get())
        .collect()
}

/// Writes `output` into `directory`, every file starting with the ROM marker line, and
/// returns the paths of its `.c` files.
///
/// # Errors
/// Returns [`BuildError::Write`].
pub fn write_output(output: &Output, directory: &Path) -> Result<Vec<PathBuf>, BuildError> {
    let marker = c_marker_line();
    fs::create_dir_all(directory).map_err(|source| write_error(directory, source))?;
    for file in &output.files {
        write_file(
            &directory.join(&file.name),
            format!("{marker}{}", file.text),
        )?;
    }
    Ok(output
        .sources()
        .map(|file| directory.join(&file.name))
        .collect())
}

/// Writes everything a game program compiles from into `directory`: the translated C (as
/// [`write_output`]), a copy of the ROM image, the C that embeds it, and the `ag_game` table
/// the player reads (`AgGame` in the abi crate). Returns the paths of the `.c` files.
///
/// # Errors
/// Returns [`BuildError::Write`], or [`BuildError::NotStepped`] for a translation without
/// stepped code (`game_options` always has it).
pub fn write_program(
    rom: &Rom,
    translation: &Translation,
    directory: &Path,
) -> Result<Vec<PathBuf>, BuildError> {
    let output = &translation.output;
    let stepped = output.stepped.as_ref().ok_or(BuildError::NotStepped)?;
    let mut sources = write_output(output, directory)?;
    write_file(&directory.join(IMAGE_FILE), rom.bytes())?;
    let image = directory.join("ag_image.c");
    write_file(&image, image_source(rom.bytes().len()))?;
    let game = directory.join("ag_game.c");
    let text = game_source(rom, translation, output.table_rows, stepped.even_addresses);
    write_file(&game, text)?;
    sources.extend([image, game]);
    Ok(sources)
}

/// The copy of the ROM image a program embeds, beside its C.
const IMAGE_FILE: &str = "ag_image.bin";

/// `ag_image.c`: the image as `ag_image`, `size` bytes, embedded whole from [`IMAGE_FILE`].
/// `#embed` is C23; clang accepts it in C11 as an extension, which is a warning.
fn image_source(size: usize) -> String {
    format!(
        "{}{GENERATED}\n#include <stdint.h>\n\n\
         /* The whole ROM image, which the player loads and checks at start. */\n\
         #pragma clang diagnostic push\n\
         #pragma clang diagnostic ignored \"-Wc23-extensions\"\n\
         const uint8_t ag_image[] = {{\n#embed \"{IMAGE_FILE}\"\n}};\n\
         #pragma clang diagnostic pop\n\n\
         _Static_assert(sizeof ag_image == {size}u, \"the embedded image changed size\");\n",
        c_marker_line()
    )
}

/// `ag_game.c`: the `ag_game` table of the program translated from `rom`, whose address
/// table has `table_rows` rows and whose stepped table `steps` entries.
fn game_source(rom: &Rom, translation: &Translation, table_rows: usize, steps: usize) -> String {
    let analysis = &translation.analysis;
    let entries: Vec<u32> = analysis.functions.keys().map(|entry| entry.get()).collect();
    let mut text = format!(
        "{}{GENERATED}\n#include \"ag_functions.h\"\n\nextern const uint8_t ag_image[];\n",
        c_marker_line()
    );
    let handlers = vector_handlers(analysis);
    let handler_array = c_array(&mut text, "ag_vector_handlers", &handlers);
    let entry_array = c_array(&mut text, "ag_function_entries", &entries);
    let sha1: Vec<String> = rom
        .sha1()
        .bytes()
        .iter()
        .map(|byte| format!("0x{byte:02X}u"))
        .collect();
    text.push_str(&format!(
        "\nconst AgGame ag_game = {{\n    \
         .abi = AG_GAME_ABI,\n    \
         .image_size = {image_size}u,\n    \
         .image = ag_image,\n    \
         .sha1 = {{ {sha1} }},\n    \
         .title = {title},\n    \
         .table = ag_table,\n    \
         .table_size = {table_rows}u,\n    \
         .steps_size = {steps}u,\n    \
         .steps = ag_steps,\n    \
         .step_entry = ag_step_entry,\n    \
         .interrupt = ag_interrupt,\n    \
         .vector_handlers = {handler_array},\n    \
         .vector_handler_count = {handler_count}u,\n    \
         .function_entry_count = {entry_count}u,\n    \
         .function_entries = {entry_array},\n    \
         .extras = 0,\n    \
         .extra_count = 0u,\n}};\n",
        image_size = rom.bytes().len(),
        sha1 = sha1.join(", "),
        title = c_string(&rom.title()),
        handler_count = handlers.len(),
        entry_count = entries.len(),
    ));
    text
}

/// Appends `values` to `text` as the static array `name` and returns the expression for a
/// pointer to it: a null pointer when `values` is empty, as C has no empty arrays.
fn c_array(text: &mut String, name: &str, values: &[u32]) -> String {
    if values.is_empty() {
        return "0".to_owned();
    }
    text.push_str(&format!("\nstatic const uint32_t {name}[] = {{\n"));
    for value in values {
        text.push_str(&format!("    0x{value:06X}u,\n"));
    }
    text.push_str("};\n");
    name.to_owned()
}

/// `text` as a C string literal; bytes other than printable ASCII, quotes and backslashes
/// as three-digit octal escapes, which unlike `\x` never run into the next character.
fn c_string(text: &str) -> String {
    let mut literal = String::from("\"");
    for byte in text.bytes() {
        match byte {
            b' '..=b'~' if !matches!(byte, b'"' | b'\\' | b'?') => {
                literal.push(char::from(byte));
            }
            _ => literal.push_str(&format!("\\{byte:03o}")),
        }
    }
    literal.push('"');
    literal
}

fn write_file(path: &Path, contents: impl AsRef<[u8]>) -> Result<(), BuildError> {
    fs::write(path, contents).map_err(|source| write_error(path, source))
}

fn write_error(path: &Path, source: io::Error) -> BuildError {
    BuildError::Write {
        path: path.to_owned(),
        source,
    }
}

/// Compiles `sources` as C11 with clang-cl on MSVC targets and clang elsewhere, in parallel,
/// with every warning an error, and links the static library `library` into the crate whose
/// build script calls it. Headers are looked up in `include`.
///
/// # Errors
/// Returns [`BuildError::NotClang`] when cc finds another compiler, and
/// [`BuildError::Compile`] when compiling or archiving fails.
pub fn compile(library: &str, include: &Path, sources: &[PathBuf]) -> Result<(), BuildError> {
    let target = env::var("TARGET").unwrap_or_default();
    clang_build(cc::Build::new(), &target, library)?
        .include(include)
        .files(sources)
        .try_compile(library)
        .map_err(|source| compile_error(library, source))
}

/// Compiles a game's `sources` with headers from `include` into the static library `library`,
/// as [`compile`] does, but the stepped files (`ag_sNNN.c`), most of the C and run only on
/// slow paths, at the optimisation level `stepped` (cc's names: "0"-"3", "s", "z") when it
/// is given; the rest at the profile's level.
///
/// # Errors
/// As [`compile`].
pub fn compile_game(
    library: &str,
    include: &Path,
    sources: &[PathBuf],
    stepped: Option<&str>,
) -> Result<(), BuildError> {
    let Some(level) = stepped else {
        return compile(library, include, sources);
    };
    let target = env::var("TARGET").unwrap_or_default();
    let (steps, rest): (Vec<&PathBuf>, Vec<&PathBuf>) =
        sources.iter().partition(|path| is_stepped_file(path));
    let objects = clang_build(cc::Build::new(), &target, library)?
        .include(include)
        .files(steps)
        .opt_level_str(level)
        .try_compile_intermediates()
        .map_err(|source| compile_error(library, source))?;
    clang_build(cc::Build::new(), &target, library)?
        .include(include)
        .files(rest)
        .objects(objects)
        .try_compile(library)
        .map_err(|source| compile_error(library, source))
}

/// Whether `path` is a stepped file the emitter wrote (`ag_s000.c`, ...; not `ag_steps.c`).
pub fn is_stepped_file(path: &Path) -> bool {
    path.file_name()
        .and_then(|name| name.to_str())
        .and_then(|name| name.strip_prefix("ag_s"))
        .and_then(|rest| rest.strip_suffix(".c"))
        .is_some_and(|number| number.bytes().all(|byte| byte.is_ascii_digit()))
}

/// Configures `build` for translated C on `target`: clang, C11, warnings as errors.
fn clang_build(mut build: cc::Build, target: &str, library: &str) -> Result<cc::Build, BuildError> {
    if target.ends_with("msvc") {
        build.prefer_clang_cl_over_msvc(true);
    } else {
        build.compiler("clang");
    }
    let tool = build
        .try_get_compiler()
        .map_err(|source| compile_error(library, source))?;
    if !tool.is_like_clang_cl() && !tool.is_like_clang() {
        return Err(BuildError::NotClang {
            path: tool.path().to_owned(),
        });
    }
    // cc's default warning level is on (-W4 / -Wall -Wextra); `warnings(false)` would pass
    // -W0 to clang-cl and silence it.
    build.std("c11").warnings_into_errors(true);
    Ok(build)
}

fn compile_error(library: &str, source: cc::Error) -> BuildError {
    BuildError::Compile {
        library: library.to_owned(),
        source,
    }
}

#[cfg(test)]
mod tests {
    use std::fs;

    use super::*;

    const TARGET: &str = if cfg!(windows) {
        "x86_64-pc-windows-msvc"
    } else {
        "x86_64-unknown-linux-gnu"
    };

    /// Compiles `text` as a library of its own outside any build script.
    fn compile_text(name: &str, text: &str) -> Result<(), BuildError> {
        let directory = env::temp_dir().join(format!("anygenesis-recomp-{name}"));
        fs::create_dir_all(&directory).expect("temp directory created");
        let source = directory.join(format!("{name}.c"));
        fs::write(&source, text).expect("source written");
        let mut build = cc::Build::new();
        build
            .target(TARGET)
            .host(TARGET)
            .opt_level(0)
            .debug(false)
            .out_dir(&directory)
            .cargo_metadata(false);
        clang_build(build, TARGET, name)?
            .file(&source)
            .try_compile(name)
            .map_err(|source| compile_error(name, source))
    }

    #[test]
    fn test_only_numbered_stepped_files_count_as_stepped() {
        let stepped = |name: &str| is_stepped_file(Path::new("c").join(name).as_path());
        assert!(stepped("ag_s000.c"));
        assert!(stepped("ag_s219.c"));
        assert!(!stepped("ag_steps.c"));
        assert!(!stepped("ag_000.c"));
        assert!(!stepped("ag_table.c"));
        assert!(!stepped("ag_s000.h"));
    }

    #[test]
    fn test_c_string_escapes_quotes_and_bytes_outside_ascii_as_octal() {
        assert_eq!(c_string("SONIC THE HEDGEHOG"), "\"SONIC THE HEDGEHOG\"");
        assert_eq!(c_string("A\"B\\C?"), "\"A\\042B\\134C\\077\"");
        assert_eq!(c_string("\u{e9}1"), "\"\\303\\2511\"");
    }

    #[test]
    fn test_c_array_of_nothing_is_a_null_pointer() {
        let mut text = String::new();
        assert_eq!(c_array(&mut text, "ag_none", &[]), "0");
        assert!(text.is_empty());
        assert_eq!(c_array(&mut text, "ag_some", &[0x200]), "ag_some");
        assert_eq!(
            text,
            "\nstatic const uint32_t ag_some[] = {\n    0x000200u,\n};\n"
        );
    }

    #[test]
    fn test_image_source_embeds_the_image_file_with_its_size() {
        let text = image_source(0x8_0000);
        assert!(text.starts_with(&c_marker_line()));
        assert!(text.contains(&format!("#embed \"{IMAGE_FILE}\"\n")));
        assert!(text.contains("sizeof ag_image == 524288u"));
    }

    #[test]
    fn test_compile_clean_source_succeeds() {
        let result = compile_text("clean", "int ag_clean(int x) { return x + 1; }\n");
        assert!(result.is_ok(), "{result:?}");
    }

    #[test]
    fn test_compile_warning_fails() {
        let text = "int ag_warns(int x) { int unused; return x; }\n";
        let result = compile_text("warns", text);
        assert!(
            matches!(result, Err(BuildError::Compile { .. })),
            "{result:?}"
        );
    }
}
