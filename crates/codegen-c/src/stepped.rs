//! Stepped native code (superset translation, Architecture Decision 6).
//!
//! Every even ROM address whose bytes decode to an instruction gets a stepped function, so no
//! jump into the ROM can miss native code. A stepped function runs its one instruction with
//! the interpreter's boundary protocol, which makes stepped code end where the interpreter
//! ends: the instruction's start noted for its device accesses (`ag_step_begin`), then
//! stalls, the latch rule, rescheduling, delivery and the scheduler at the next boundary
//! where the budget ran out at its end (`ag_step_end`). An instruction that cannot reach a
//! device, write SR, take an exception or reset takes the fast path: it calls the runtime
//! only once the budget ran out (`ag_step_late`). Then it tail-calls the next address's
//! stepped function, which therefore needs no check of its own. At a table row it hands over
//! to the translated function there, unless a check point's slow path just entered it
//! (`AG_STEP_FIRST`). Entries from anywhere else (the dispatcher, the top level, a check
//! after an access) go through `ag_step_entry`, which runs the scheduler first, and so does
//! stepped code where a call or STOP came back.
//!
//! The superset keeps an address when its instruction transfers control or the instruction
//! after it is kept, so a straight-line run that reaches undecodable bytes or the ROM end is
//! dropped; analysed instructions are always kept.

use std::collections::{BTreeMap, BTreeSet};

use anygenesis_analysis::Analysis;
use anygenesis_ir::{Control, Lifted, Op, Value, exception_entry, interrupt_entry_at, lift};
use anygenesis_shared::Address;

use crate::{
    EmitOptions,
    function::{function_name, leaving_ahead, static_cost},
    printer::{ADDRESS_MASK, Printer, constant, may_reach_bus, used_temps},
};

const GENERATED: &str = "/* Generated by AnyGenesis. Do not edit. */";

/// The interrupt levels `ag_interrupt` takes.
const LEVELS: std::ops::RangeInclusive<u8> = 1..=7;

/// What the superset translation found and kept.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct SteppedStats {
    /// Even addresses in the image.
    pub even_addresses: usize,
    /// Those whose bytes decode to an instruction that lies wholly in the image.
    pub decodable: usize,
    /// Decodable addresses with a stepped function.
    pub kept: usize,
    /// Decodable addresses whose straight-line run reaches undecodable bytes or the image end
    /// before any control transfer.
    pub pruned: usize,
    /// Analysed instructions kept although the rule alone would drop them.
    pub forced: usize,
    /// Kept instructions on the fast path.
    pub fast: usize,
}

/// The stepped C: function files, the file with the `ag_steps` table and `ag_interrupt`, and
/// what was kept.
#[derive(Debug)]
pub struct Stepped {
    pub chunks: Vec<String>,
    pub table: String,
    pub stats: SteppedStats,
}

/// The C name of the stepped function at `address`, after the symbol prefix.
pub fn step_name(prefix: &str, address: u32) -> String {
    format!("{prefix}s_{address:06X}")
}

/// The stepped function of `lifted` alone, as the superset emits it but with no table row
/// to hand over at and every successor through `ag_step_lookup`, for an image of
/// `image_size` bytes. For tests that run one stepped instruction.
pub fn emit_stepped_instruction(lifted: &Lifted, image_size: u32, prefix: &str) -> String {
    let mut called = BTreeSet::new();
    let mut emitter = StepEmitter {
        prefix,
        image_size,
        kept: &[],
        called: &mut called,
        fast: is_fast(lifted, image_size),
        latch: lifted.latch,
    };
    emitter.function(lifted, None)
}

fn step_prototype(prefix: &str, address: u32) -> String {
    format!(
        "uint32_t {}(AgState *s, uint32_t pc)",
        step_name(prefix, address)
    )
}

/// The declaration of the stepped function at `address`, through the `AgFn` typedef.
fn step_declaration(prefix: &str, address: u32) -> String {
    format!("AgFn {};\n", step_name(prefix, address))
}

/// The C name of the checked entry into stepped code, after the symbol prefix.
pub fn entry_name(prefix: &str) -> String {
    format!("{prefix}ag_step_entry")
}

/// The C prototype of `ag_interrupt` (`AgInterrupt` in the abi crate), without a semicolon.
pub fn interrupt_prototype(prefix: &str) -> String {
    format!("uint32_t {prefix}ag_interrupt(AgState *s, uint32_t level, uint32_t pc)")
}

/// The instruction at `address` when it decodes, lifts and lies wholly in `image`.
fn decode(image: &[u8], address: u32) -> Option<Lifted> {
    let instruction = anygenesis_m68k::decode_at(image, address as usize).ok()?;
    let lifted = lift(&instruction, Address::new(address)).ok()?;
    (lifted.next().get() as usize <= image.len()).then_some(lifted)
}

fn transfers_control(lifted: &Lifted) -> bool {
    lifted
        .body
        .ops
        .iter()
        .any(|op| matches!(op, Op::Branch { .. } | Op::Exit(_)))
}

fn raises_or_resets(lifted: &Lifted) -> bool {
    lifted.body.ops.iter().any(|op| {
        matches!(
            op,
            Op::ResetDevices
                | Op::Branch {
                    control: Control::Exception { .. },
                    ..
                }
                | Op::Exit(Control::Exception { .. })
        )
    })
}

/// Which even addresses of `image` get a stepped function, indexed by address / 2, and the
/// counts behind it (`fast` stays 0: only emitting decides it).
pub fn superset(image: &[u8], analysis: &Analysis) -> (Vec<bool>, SteppedStats) {
    let even = image.len() / 2;
    let mut stats = SteppedStats {
        even_addresses: even,
        ..SteppedStats::default()
    };
    let mut kept = vec![false; even];
    // From the end, so the instruction after each one is decided first.
    for index in (0..even).rev() {
        let address = (index * 2) as u32;
        let Some(lifted) = decode(image, address) else {
            continue;
        };
        stats.decodable += 1;
        let next = lifted.next().get() as usize;
        let natural = transfers_control(&lifted)
            || (next < image.len() && next.is_multiple_of(2) && kept[next / 2]);
        let analysed = analysis.instructions.contains_key(&Address::new(address));
        kept[index] = natural || analysed;
        if !kept[index] {
            stats.pruned += 1;
            continue;
        }
        stats.kept += 1;
        if !natural {
            stats.forced += 1;
        }
    }
    (kept, stats)
}

/// Emits the stepped functions of `image`, their table and the interrupt entry. `rows` maps
/// every table row to the translated function that holds it.
pub fn emit(
    image: &[u8],
    analysis: &Analysis,
    rows: &BTreeMap<Address, Address>,
    options: &EmitOptions,
) -> Stepped {
    let prefix = options.symbol_prefix.as_str();
    let (kept, mut stats) = superset(image, analysis);
    let even = kept.len();

    let mut chunks = Vec::new();
    let mut text = String::new();
    let mut lines = 0;
    let mut called = BTreeSet::new();
    for index in (0..even).filter(|&index| kept[index]) {
        let address = (index * 2) as u32;
        let lifted = decode(image, address).expect("kept addresses decode");
        let mut emitter = StepEmitter {
            prefix,
            image_size: image.len() as u32,
            kept: &kept,
            called: &mut called,
            fast: is_fast(&lifted, image.len() as u32),
            latch: lifted.latch,
        };
        let function = emitter.function(&lifted, rows.get(&lifted.address).copied());
        if emitter.fast {
            stats.fast += 1;
        }
        lines += function.lines().count() + 1;
        text.push('\n');
        text.push_str(&function);
        if lines >= options.chunk_lines {
            chunks.push(chunk(prefix, &std::mem::take(&mut text), &called));
            called.clear();
            lines = 0;
        }
    }
    if !text.is_empty() {
        chunks.push(chunk(prefix, &text, &called));
    }
    Stepped {
        chunks,
        table: table_file(prefix, &kept, image.len() as u32),
        stats,
    }
}

/// Whether `lifted` needs the runtime only once the budget ran out: it reaches no device,
/// writes no SR, raises no exception and does not reset.
fn is_fast(lifted: &Lifted, image_size: u32) -> bool {
    !may_reach_bus(&lifted.body, image_size)
        && !lifted.body.writes_sr()
        && !raises_or_resets(lifted)
}

/// One file of stepped functions, with the prototypes of the ones it tail-calls.
fn chunk(prefix: &str, text: &str, called: &BTreeSet<u32>) -> String {
    let mut out =
        format!("{GENERATED}\n#include \"ag_runtime.h\"\n#include \"ag_functions.h\"\n\n");
    for &address in called {
        out.push_str(&step_declaration(prefix, address));
    }
    out.push_str(text);
    out
}

/// The `ag_steps` table, indexed by address / 2, the checked entry and `ag_interrupt`.
fn table_file(prefix: &str, kept: &[bool], image_size: u32) -> String {
    let mut out =
        format!("{GENERATED}\n#include \"ag_runtime.h\"\n#include \"ag_functions.h\"\n\n");
    for (index, _) in kept.iter().enumerate().filter(|(_, kept)| **kept) {
        out.push_str(&step_declaration(prefix, (index * 2) as u32));
    }
    out.push_str(&format!("\nAgFn *const {prefix}ag_steps[] = {{\n"));
    for (index, kept) in kept.iter().enumerate() {
        if *kept {
            out.push_str(&format!("    {},\n", step_name(prefix, (index * 2) as u32)));
        } else {
            out.push_str("    0,\n");
        }
    }
    if kept.is_empty() {
        out.push_str("    0,\n");
    }
    out.push_str("};\n\n");
    out.push_str(&format!(
        "const uint32_t {prefix}ag_steps_size = {}u;\n\n",
        kept.len()
    ));
    out.push_str(&checked_entry(prefix));
    out.push_str(&interrupt_entry(prefix, image_size));
    out
}

/// `ag_step_entry`: the scheduler where the budget ran out, then the stepped function of
/// `pc` (its `AG_STEP_FIRST` kept). What the dispatcher hands out for stepped code.
fn checked_entry(prefix: &str) -> String {
    format!(
        "uint32_t {}(AgState *s, uint32_t pc)\n{{\n    \
         uint32_t ag_a = pc & AG_ADDRESS_MASK;\n    \
         AG_STEP_CHECK(s, ag_a);\n    \
         AG_TAIL return {prefix}ag_steps[ag_a >> 1](s, pc);\n}}\n\n",
        entry_name(prefix)
    )
}

/// `ag_interrupt`: the IR's interrupt entry sequence for each level, with the interrupted pc
/// bound to its input.
fn interrupt_entry(prefix: &str, image_size: u32) -> String {
    let mut out = format!(
        "{}\n{{\n    switch (level) {{\n",
        interrupt_prototype(prefix)
    );
    for level in LEVELS {
        // The runtime passes 1-7 only.
        if level == *LEVELS.end() {
            out.push_str(&format!("    default: /* {level} */ {{\n"));
        } else {
            out.push_str(&format!("    case {level}u: {{\n"));
        }
        let (body, pc) = interrupt_entry_at(level);
        let printer = Printer {
            body: &body,
            prefix: "e",
            rom_size: image_size,
            ahead: "0",
        };
        let used = used_temps(&body);
        out.push_str(&format!("        uint32_t e{} = pc;\n", pc.index()));
        for op in &body.ops {
            if let Op::Exit(Control::JumpIndirect(handler)) = *op {
                out.push_str(&format!(
                    "        return {} & {};\n",
                    printer.value(handler),
                    constant(ADDRESS_MASK)
                ));
            } else if let Some(statement) = printer.op(op, &used) {
                out.push_str(&format!("        {statement}\n"));
            }
        }
        out.push_str("    }\n");
    }
    out.push_str("    }\n}\n");
    out
}

struct StepEmitter<'a> {
    prefix: &'a str,
    image_size: u32,
    kept: &'a [bool],
    /// The stepped functions the current chunk calls.
    called: &'a mut BTreeSet<u32>,
    /// Calls the runtime only once the budget ran out (`ag_step_late`).
    fast: bool,
    latch: u16,
}

impl StepEmitter<'_> {
    /// The stepped function of `lifted`; `owner` is the translated function that holds its
    /// address as a table row, if any.
    fn function(&mut self, lifted: &Lifted, owner: Option<Address>) -> String {
        let address = lifted.address.get();
        let body = &lifted.body;
        let a = constant(address);
        let mut out = vec![step_prototype(self.prefix, address), "{".to_owned()];
        match owner {
            Some(owner) => {
                out.push("    if (!(pc & AG_STEP_FIRST))".to_owned());
                out.push(format!(
                    "        AG_TAIL return {}(s, {a});",
                    function_name(self.prefix, owner)
                ));
            }
            None => out.push("    (void)pc;".to_owned()),
        }
        if self.fast {
            out.push("    int32_t ag_c0 = s->cycles;".to_owned());
        } else {
            out.push("    ag_step_begin(s);".to_owned());
        }
        let base = static_cost(lifted);
        out.push(format!("    AG_CYCLES(s, {base});"));
        let ahead = base.to_string();
        let printer = Printer {
            body,
            prefix: "t",
            rom_size: self.image_size,
            ahead: &ahead,
        };
        let used = used_temps(body);
        let mut charged = Vec::new();
        out.push("    {".to_owned());
        for op in &body.ops {
            match *op {
                Op::Branch { condition, control } => {
                    out.push(format!("        if ({}) {{", printer.value(condition)));
                    let path = lifted.cycles.leaving(&control);
                    if path != base {
                        let extra = i32::from(path) - i32::from(base);
                        out.push(format!("            AG_CYCLES(s, {extra});"));
                    }
                    let exception_ahead = leaving_ahead(true, path, &charged);
                    let lines = self.control(control, &printer, &exception_ahead);
                    out.extend(indented(12, lines));
                    out.push("        }".to_owned());
                }
                Op::Exit(control) => {
                    let path = lifted.cycles.leaving(&control);
                    let exception_ahead = leaving_ahead(true, path, &charged);
                    let lines = self.control(control, &printer, &exception_ahead);
                    out.extend(indented(8, lines));
                }
                Op::Cycles { value } => {
                    charged.push(printer.value(value));
                    if let Some(statement) = printer.op(op, &used) {
                        out.push(format!("        {statement}"));
                    }
                }
                _ => {
                    if let Some(statement) = printer.op(op, &used) {
                        out.push(format!("        {statement}"));
                    }
                }
            }
        }
        out.push("    }".to_owned());
        if body.falls_through() {
            let lines = self.go_to(lifted.next().get());
            out.extend(indented(4, lines));
        }
        out.push("}".to_owned());
        out.join("\n") + "\n"
    }

    fn control(&mut self, control: Control, printer: &Printer<'_>, ahead: &str) -> Vec<String> {
        let mask = constant(ADDRESS_MASK);
        match control {
            Control::Jump(target) => self.go_to(target.get()),
            Control::JumpIndirect(value) => {
                let mut lines = vec![
                    "{".to_owned(),
                    format!("    uint32_t ag_t = {} & {mask};", printer.value(value)),
                ];
                lines.extend(indented(4, self.go_dynamic("ag_t")));
                lines.push("}".to_owned());
                lines
            }
            Control::Call {
                target,
                return_address,
            } => self.call(&constant(target.get()), return_address.get()),
            Control::CallIndirect {
                target,
                return_address,
            } => {
                let mut lines = vec![
                    "{".to_owned(),
                    format!("    uint32_t ag_t = {} & {mask};", printer.value(target)),
                ];
                lines.extend(indented(4, self.call("ag_t", return_address.get())));
                lines.push("}".to_owned());
                lines
            }
            Control::Return { target, .. } => {
                let target = format!("{} & {mask}", printer.value(target));
                if self.fast {
                    vec![
                        "{".to_owned(),
                        format!("    uint32_t ag_t = {target};"),
                        "    if (s->cycles <= 0)".to_owned(),
                        format!("        return {};", self.late("ag_t")),
                        "    return ag_t;".to_owned(),
                        "}".to_owned(),
                    ]
                } else {
                    vec![format!(
                        "return ag_step_end(s, {target}, {}u, AG_STEP_GO);",
                        self.latch
                    )]
                }
            }
            Control::Exception { vector, pc } => self.exception(vector, pc, ahead),
            Control::Stop { resume } => {
                let r = constant(resume.get());
                let mut lines = vec![
                    "{".to_owned(),
                    format!(
                        "    (void)ag_step_end(s, {r}, {}u, AG_STEP_STOP);",
                        self.latch
                    ),
                    format!("    uint32_t ag_n = ag_stop(s, {r});"),
                    format!("    if (ag_n != {r})"),
                    "        return ag_n;".to_owned(),
                    "}".to_owned(),
                    format!("AG_STEP_CHECK(s, {r});"),
                ];
                lines.extend(self.tail_call(resume.get()));
                lines
            }
        }
    }

    /// A call of `target` (a C expression) returning to `return_address`, then on there.
    fn call(&mut self, target: &str, return_address: u32) -> Vec<String> {
        let r = constant(return_address);
        let mut lines = vec![
            "{".to_owned(),
            format!(
                "    (void)ag_step_end(s, {r}, {}u, AG_STEP_CALL);",
                self.latch
            ),
            format!("    AgFn *ag_f = ag_lookup(s, {target});"),
            format!("    uint32_t ag_n = ag_f(s, {target});"),
            format!("    if (ag_n != {r})"),
            "        return ag_n;".to_owned(),
            "}".to_owned(),
            // The callee may come back with the budget spent.
            format!("AG_STEP_CHECK(s, {r});"),
        ];
        lines.extend(self.tail_call(return_address));
        lines
    }

    /// The exception entry sequence inline, then on at the handler.
    fn exception(&mut self, vector: u8, pc: Address, ahead: &str) -> Vec<String> {
        let entry = exception_entry(vector, pc);
        let printer = Printer {
            body: &entry,
            prefix: "e",
            rom_size: self.image_size,
            ahead,
        };
        let used = used_temps(&entry);
        let mut lines = vec!["{".to_owned()];
        let mut handler = None;
        for op in &entry.ops {
            if let Op::Exit(Control::JumpIndirect(value)) = *op {
                handler = Some(value);
            } else if let Some(statement) = printer.op(op, &used) {
                lines.push(format!("    {statement}"));
            }
        }
        let handler: Value = handler.expect("an exception entry leaves through its vector");
        lines.push(format!(
            "    uint32_t ag_t = {} & {};",
            printer.value(handler),
            constant(ADDRESS_MASK)
        ));
        lines.extend(indented(4, self.go_dynamic("ag_t")));
        lines.push("}".to_owned());
        lines
    }

    /// The instruction's end, then on at the constant `target`.
    fn go_to(&mut self, target: u32) -> Vec<String> {
        let mut lines = self.end(&constant(target));
        lines.extend(self.tail_call(target));
        lines
    }

    /// The instruction's end, then on at `target`, a C variable.
    fn go_dynamic(&mut self, target: &str) -> Vec<String> {
        let mut lines = self.end(target);
        lines.push(format!("AG_STEP_JUMP(s, {target});"));
        lines
    }

    /// The instruction's end before going on at `target`: delivery there if due, then the
    /// scheduler there if the budget ran out.
    fn end(&self, target: &str) -> Vec<String> {
        let end = if self.fast {
            "AG_STEP_FAST_END"
        } else {
            "AG_STEP_END"
        };
        vec![format!("{end}(s, {target}, {}u);", self.latch)]
    }

    /// The fast path's end call once the budget ran out, going on at `target`.
    fn late(&self, target: &str) -> String {
        format!(
            "ag_step_late(s, {target}, {}u, (uint32_t)(ag_c0 - s->cycles))",
            self.latch
        )
    }

    /// The tail call on at the constant `target`: its stepped function, else the lookup.
    fn tail_call(&mut self, target: u32) -> Vec<String> {
        let t = constant(target);
        let kept = target.is_multiple_of(2)
            && target < self.image_size
            && self
                .kept
                .get((target / 2) as usize)
                .copied()
                .unwrap_or(false);
        if kept {
            self.called.insert(target);
            vec![format!(
                "AG_TAIL return {}(s, {t});",
                step_name(self.prefix, target)
            )]
        } else {
            vec![format!("AG_STEP_JUMP(s, {t});")]
        }
    }
}

fn indented(indent: usize, lines: Vec<String>) -> Vec<String> {
    lines
        .into_iter()
        .map(|line| format!("{:indent$}{line}", ""))
        .collect()
}
