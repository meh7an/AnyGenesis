//! The whole program: headers, function files cut at a line budget, the address table, and
//! the stepped files when they are asked for.

use std::collections::{BTreeMap, BTreeSet};

use anygenesis_analysis::{Analysis, FlagLiveness, Function, Origin};
use anygenesis_ir::{Lifted, SR_MASK, SR_SUPERVISOR, lift};
use anygenesis_shared::Address;

use crate::{
    EmitOptions, Output, OutputFile,
    function::{emit_function, function_name, prototype},
    printer::constant,
    stepped,
};

const RUNTIME_HEADER: &str = include_str!("ag_runtime.h");
const PATCH_HEADER: &str = include_str!("ag_patch.h");
const GENERATED: &str = "/* Generated by AnyGenesis. Do not edit. */";

/// What every function's emission reads.
#[derive(Debug)]
pub struct Context<'a> {
    pub analysis: &'a Analysis,
    pub liveness: &'a FlagLiveness<'a>,
    pub options: &'a EmitOptions,
    /// The analysed handler of each exception vector.
    pub handlers: BTreeMap<u8, Address>,
}

impl Context<'_> {
    /// Returns the instruction at `address` with dead flag computations pruned.
    pub fn pruned(&self, address: Address) -> Lifted {
        if let Some(lifted) = self.liveness.lifted(address) {
            return self.liveness.prune(lifted);
        }
        // FlagLiveness lifts every analysed instruction, and every decoded instruction
        // lifts (the ir crate's exhaustive test), so neither fallback is reached.
        let instruction = &self.analysis.instructions[&address];
        lift(instruction, address).expect("decoded instructions always lift")
    }

    /// Returns the function entered at `entry` when it is translated: an entry the analysis
    /// could not decode has no block and no C function, so it goes through the dispatcher.
    pub fn function(&self, entry: Address) -> Option<&Function> {
        self.analysis
            .functions
            .get(&entry)
            .filter(|_| self.analysis.blocks.contains_key(&entry))
    }

    /// Returns whether the instruction at `address` is in a translated function.
    pub fn translates(&self, address: Address) -> bool {
        self.analysis.instructions.contains_key(&address)
            && self.functions().any(|function| {
                function.blocks.iter().any(|start| {
                    self.analysis
                        .blocks
                        .get(start)
                        .is_some_and(|block| (block.start..block.end).contains(&address))
                })
            })
    }

    /// Returns every translated function in address order.
    pub fn functions(&self) -> impl Iterator<Item = &Function> {
        self.analysis
            .functions
            .values()
            .filter(|function| self.analysis.blocks.contains_key(&function.entry))
    }
}

pub fn emit(
    analysis: &Analysis,
    liveness: &FlagLiveness<'_>,
    options: &EmitOptions,
    image: &[u8],
) -> Output {
    let context = Context {
        analysis,
        liveness,
        options,
        handlers: handlers(analysis),
    };
    let mut table: BTreeMap<Address, Address> = context
        .functions()
        .map(|function| (function.entry, function.entry))
        .collect();
    let mut chunks: Vec<String> = Vec::new();
    let mut chunk = String::new();
    let mut chunk_lines = 0;
    for function in context.functions() {
        let emitted = emit_function(&context, function);
        for address in emitted.resume {
            table.entry(address).or_insert(function.entry);
        }
        if chunk_lines > 0 && chunk_lines >= options.chunk_lines {
            chunks.push(std::mem::take(&mut chunk));
            chunk_lines = 0;
        }
        chunk.push('\n');
        chunk.push_str(&emitted.text);
        chunk_lines += emitted.text.lines().count() + 1;
    }
    if !chunk.is_empty() {
        chunks.push(chunk);
    }
    let mut files = vec![
        OutputFile {
            name: "ag_state.h".to_owned(),
            text: anygenesis_abi::header(),
        },
        OutputFile {
            name: "ag_runtime.h".to_owned(),
            text: runtime_header(),
        },
        OutputFile {
            name: "ag_functions.h".to_owned(),
            text: functions_header(&context),
        },
    ];
    for (index, text) in chunks.into_iter().enumerate() {
        files.push(OutputFile {
            name: format!("ag_{index:03}.c"),
            text: format!(
                "{GENERATED}\n#include \"ag_runtime.h\"\n#include \"ag_functions.h\"\n{text}"
            ),
        });
    }
    if !options.patches.is_empty() {
        files.push(OutputFile {
            name: "ag_patch.h".to_owned(),
            text: PATCH_HEADER.to_owned(),
        });
    }
    files.push(OutputFile {
        name: "ag_table.c".to_owned(),
        text: table_file(&options.symbol_prefix, &table),
    });
    let mut unplaced_patches = Vec::new();
    let stepped = options.stepped.then(|| {
        let stepped = stepped::emit(image, analysis, &table, options);
        for (index, text) in stepped.chunks.into_iter().enumerate() {
            files.push(OutputFile {
                name: format!("ag_s{index:03}.c"),
                text,
            });
        }
        files.push(OutputFile {
            name: "ag_steps.c".to_owned(),
            text: stepped.table,
        });
        unplaced_patches = stepped.unplaced;
        stepped.stats
    });
    if !options.stepped {
        unplaced_patches = options
            .patches
            .keys()
            .copied()
            .filter(|&address| !context.translates(address))
            .collect();
    }
    Output {
        files,
        table_rows: table.len(),
        stepped,
        unplaced_patches,
    }
}

/// Maps each exception vector to the translated function analysed from it.
fn handlers(analysis: &Analysis) -> BTreeMap<u8, Address> {
    let mut handlers = BTreeMap::new();
    for function in analysis
        .functions
        .values()
        .filter(|function| analysis.blocks.contains_key(&function.entry))
    {
        for origin in &function.origins {
            if let Origin::Vector(vector) = origin {
                handlers.insert(*vector, function.entry);
            }
        }
    }
    handlers
}

/// The fixed header with the constants the IR and the abi crate define.
fn runtime_header() -> String {
    // RAM_SIZE is 64 KiB.
    let ram_mask = anygenesis_abi::RAM_SIZE as u32 - 1;
    RUNTIME_HEADER
        .replace("@SR_MASK@", &constant(SR_MASK))
        .replace("@SR_SUPERVISOR@", &constant(SR_SUPERVISOR))
        .replace("@RAM_MASK@", &constant(ram_mask))
}

fn functions_header(context: &Context<'_>) -> String {
    let prefix = &context.options.symbol_prefix;
    let guard = format!("{}AG_FUNCTIONS_H", prefix.to_ascii_uppercase());
    let mut text = format!("{GENERATED}\n#ifndef {guard}\n#define {guard}\n\n");
    text.push_str("#include \"ag_state.h\"\n\n");
    for function in context.functions() {
        text.push_str(&prototype(prefix, function.entry));
        text.push_str(";\n");
    }
    text.push_str("\n/* Every function entry and resume point, by address. */\n");
    text.push_str(&format!("extern const AgEntry {prefix}ag_table[];\n"));
    text.push_str(&format!("extern const uint32_t {prefix}ag_table_size;\n\n"));
    let patches: BTreeSet<&str> = context
        .options
        .patches
        .values()
        .map(|patch| patch.function.as_str())
        .collect();
    if !patches.is_empty() {
        text.push_str("/* The code patches (ag_patch.h). */\n");
        for function in patches {
            text.push_str(&format!("uint32_t {function}(AgState *s, uint32_t pc);\n"));
        }
        text.push('\n');
    }
    if context.options.stepped {
        text.push_str(
            "/* The stepped function of every even ROM address, index address / 2; null where \
             the superset kept none. */\n",
        );
        text.push_str(&format!("#define AG_STEPS {prefix}ag_steps\n"));
        text.push_str(&format!("extern AgFn *const {prefix}ag_steps[];\n"));
        text.push_str(&format!("extern const uint32_t {prefix}ag_steps_size;\n"));
        let entry = stepped::entry_name(prefix);
        text.push_str(
            "/* Stepped code entered from anywhere but the stepped function before. */\n",
        );
        text.push_str(&format!("#define AG_STEP_ENTRY {entry}\nAgFn {entry};\n"));
        text.push_str(&format!("{};\n\n", stepped::interrupt_prototype(prefix)));
    }
    text.push_str("#endif\n");
    text
}

fn table_file(prefix: &str, table: &BTreeMap<Address, Address>) -> String {
    let mut text = format!("{GENERATED}\n#include \"ag_functions.h\"\n\n");
    text.push_str(&format!("const AgEntry {prefix}ag_table[] = {{\n"));
    for (address, entry) in table {
        text.push_str(&format!(
            "    {{ {}, {} }},\n",
            constant(address.get()),
            function_name(prefix, *entry)
        ));
    }
    if table.is_empty() {
        text.push_str("    { 0x0u, 0 },\n");
    }
    text.push_str("};\n\n");
    text.push_str(&format!(
        "const uint32_t {prefix}ag_table_size = {}u;\n",
        table.len()
    ));
    text
}
