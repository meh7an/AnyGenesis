//! Builds a game program from a ROM in its cache entry: discover its code (with a profile
//! run at the furthest stage), translate, write the C, compile it on every core, link it
//! with the player library into one native program.

use std::{
    fs,
    path::{Path, PathBuf},
    process::Output,
    sync::{
        Mutex,
        atomic::{AtomicBool, AtomicUsize, Ordering},
    },
    thread,
    time::Instant,
};

use anygenesis_recomp::build;
use anygenesis_rom::Rom;
use anyhow::{Context, Result, bail};

use crate::{
    cache::Entry,
    profile::{self, Discovery},
    toolchain::{EXE_SUFFIX, Toolchain},
};

/// The C `main` of a game program, which hands over to the player.
const MAIN_SOURCE: &str = "/* Generated by AnyGenesis. Do not edit. */\n\
                           int ag_player_main(void);\n\n\
                           int main(void)\n{\n    return ag_player_main();\n}\n";

/// The program in a cache entry.
pub fn program(entry: &Entry) -> PathBuf {
    entry.folder.join(format!("game{EXE_SUFFIX}"))
}

/// Builds the program for `rom` into `entry` with `toolchain`, discovering code as far as
/// `discovery` goes and linking the player library at `player`, and marks the entry
/// finished. Prints what each step took.
///
/// # Errors
/// The profile run, writing the files, a compile or link that fails (with the compiler's
/// output), or finishing the entry.
pub fn build_program(
    rom: &Rom,
    entry: &Entry,
    toolchain: &Toolchain,
    player: &Path,
    discovery: Discovery,
) -> Result<()> {
    entry.invalidate()?;
    let (sources, objects) = (entry.folder.join("c"), entry.folder.join("obj"));
    for folder in [&sources, &objects] {
        remove_folder(folder)?;
        fs::create_dir_all(folder).with_context(|| format!("creating {}", folder.display()))?;
    }
    let started = Instant::now();
    let analysis = profile::analyze(rom, discovery, &entry.folder)?;
    let analysed = started.elapsed();
    let translation = build::translate_analysis(
        rom,
        analysis,
        build::game_liveness(),
        &build::game_options(),
    );
    let translated = started.elapsed();
    let mut files = build::write_program(rom, &translation, &sources)?;
    let main = sources.join("ag_main.c");
    fs::write(&main, MAIN_SOURCE).with_context(|| format!("writing {}", main.display()))?;
    files.push(main);
    let written = started.elapsed();
    let jobs = compile_jobs(&files, &objects)?;
    compile_all(toolchain, &jobs)?;
    let compiled = started.elapsed();
    let objects: Vec<PathBuf> = jobs.into_iter().map(|job| job.object).collect();
    let exe = program(entry);
    let mut link = toolchain.link(&objects, player, &exe, &entry.folder.join("link.rsp"))?;
    let output = link
        .output()
        .with_context(|| format!("running {}", toolchain.compiler().display()))?;
    check(&output, "linking the game")?;
    let linked = started.elapsed();
    entry.finish()?;
    println!(
        "built in {:.1} s: discovered ({}) {:.1} s, translated {:.1} s, C written {:.1} s, {} \
         files compiled {:.1} s, linked {:.1} s",
        linked.as_secs_f64(),
        discovery.name(),
        analysed.as_secs_f64(),
        (translated - analysed).as_secs_f64(),
        (written - translated).as_secs_f64(),
        objects.len(),
        (compiled - written).as_secs_f64(),
        (linked - compiled).as_secs_f64(),
    );
    Ok(())
}

/// One file to compile.
#[derive(Debug)]
struct Job {
    source: PathBuf,
    object: PathBuf,
    /// Bytes in the source, to start the largest first.
    size: u64,
    stepped: bool,
}

/// The compile jobs for `sources` into `objects`, largest first so the last one to finish
/// is a small one.
fn compile_jobs(sources: &[PathBuf], objects: &Path) -> Result<Vec<Job>> {
    let mut jobs = Vec::with_capacity(sources.len());
    for source in sources {
        let stem = source
            .file_stem()
            .with_context(|| format!("{} has no file name", source.display()))?;
        let mut object = objects.join(stem);
        object.set_extension(if cfg!(windows) { "obj" } else { "o" });
        let size = fs::metadata(source)
            .with_context(|| format!("reading {}", source.display()))?
            .len();
        jobs.push(Job {
            source: source.clone(),
            object,
            size,
            stepped: build::is_stepped_file(source),
        });
    }
    jobs.sort_by_key(|job| std::cmp::Reverse(job.size));
    Ok(jobs)
}

/// Compiles every job, one compiler process per core at a time; stops starting new ones
/// after the first failure.
fn compile_all(toolchain: &Toolchain, jobs: &[Job]) -> Result<()> {
    let workers = thread::available_parallelism().map_or(1, |count| count.get());
    let next = AtomicUsize::new(0);
    let failed = AtomicBool::new(false);
    let failure: Mutex<Option<anyhow::Error>> = Mutex::new(None);
    thread::scope(|scope| {
        for _ in 0..workers.min(jobs.len()) {
            scope.spawn(|| {
                while !failed.load(Ordering::Relaxed) {
                    let Some(job) = jobs.get(next.fetch_add(1, Ordering::Relaxed)) else {
                        break;
                    };
                    let result = toolchain
                        .compile(&job.source, &job.object, job.stepped)
                        .output()
                        .with_context(|| format!("running {}", toolchain.compiler().display()))
                        .and_then(|output| {
                            check(&output, &format!("compiling {}", job.source.display()))
                        });
                    if let Err(error) = result {
                        failed.store(true, Ordering::Relaxed);
                        failure
                            .lock()
                            .unwrap_or_else(std::sync::PoisonError::into_inner)
                            .get_or_insert(error);
                    }
                }
            });
        }
    });
    match failure
        .into_inner()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
    {
        Some(error) => Err(error),
        None => Ok(()),
    }
}

/// Fails with the tool's output unless it succeeded.
fn check(output: &Output, what: &str) -> Result<()> {
    if output.status.success() {
        return Ok(());
    }
    bail!(
        "{what} failed ({}):\n{}{}",
        output.status,
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

fn remove_folder(folder: &Path) -> Result<()> {
    match fs::remove_dir_all(folder) {
        Ok(()) => Ok(()),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error).with_context(|| format!("removing {}", folder.display())),
    }
}
