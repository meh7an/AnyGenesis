//! Builds a game program from a ROM in its cache entry: discover its code (with a profile
//! run at the furthest stage), translate with the code patches placed, write the C (the
//! patch packs' own C beside it), compile it with Zig on every core, link it with the player
//! library into one native program.

use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
    process::Output,
    sync::{
        Mutex,
        atomic::{AtomicBool, AtomicUsize, Ordering},
    },
    thread,
    time::Instant,
};

use anygenesis_patch::{CodePatches, When};
use anygenesis_recomp::build::{self, Extra};
use anygenesis_rom::Rom;
use anygenesis_shared::{Address, c_marker_line};
use anyhow::{Context, Result, bail};

use crate::{
    cache::Entry,
    profile::{self, Discovery},
    progress::{self, Phase},
    toolchain::{EXE_SUFFIX, Toolchain},
};

/// The C `main` of a game program, which hands over to the player.
const MAIN_SOURCE: &str = "/* Generated by AnyGenesis. Do not edit. */\n\
                           int ag_player_main(void);\n\n\
                           int main(void)\n{\n    return ag_player_main();\n}\n";

/// The program in a cache entry.
pub fn program(entry: &Entry) -> PathBuf {
    entry.folder.join(format!("game{EXE_SUFFIX}"))
}

/// Builds the program for `rom` into `entry` with `toolchain` and its player library,
/// discovering code as far as `discovery` goes, with the code patches `code`, and marks the
/// entry finished. Prints what each step took.
///
/// # Errors
/// The profile run, a code patch at an address no code holds, writing the files, a compile
/// or link that fails (with the compiler's output), or finishing the entry.
pub fn build_program(
    rom: &Rom,
    entry: &Entry,
    toolchain: &Toolchain,
    discovery: Discovery,
    code: &CodePatches,
) -> Result<()> {
    entry.invalidate()?;
    let (sources, objects) = (entry.folder.join("c"), entry.folder.join("obj"));
    let scratch = entry.folder.join("zig-local");
    remove_folder(&scratch)?;
    for folder in [&sources, &objects] {
        remove_folder(folder)?;
        fs::create_dir_all(folder).with_context(|| format!("creating {}", folder.display()))?;
    }
    let started = Instant::now();
    progress::phase(Phase::Profile);
    let analysis = profile::analyze(rom, discovery, &entry.folder)?;
    let analysed = started.elapsed();
    let patches: BTreeMap<Address, build::CodePatch> = code
        .patches
        .iter()
        .map(|patch| {
            let placed = build::CodePatch {
                function: patch.function.clone(),
                cycles: patch.cycles,
            };
            (Address::new(patch.address), placed)
        })
        .collect();
    progress::phase(Phase::Translate);
    let (liveness, options) = build::patched_game(patches);
    let translation = build::translate_analysis(rom, analysis, liveness, &options);
    if let Some(address) = translation.output.unplaced_patches.first() {
        bail!(
            "no code is at {:#08x} for the code patch there: patch an even address whose bytes \
             decode to an instruction",
            address.get()
        );
    }
    let translated = started.elapsed();
    let mut files = build::write_program(rom, &translation, &extras(code), &sources)?;
    files.extend(write_patch_sources(code, &sources)?);
    let main = sources.join("ag_main.c");
    fs::write(&main, MAIN_SOURCE).with_context(|| format!("writing {}", main.display()))?;
    files.push(main);
    let written = started.elapsed();
    let jobs = compile_jobs(&files, &objects)?;
    compile_all(toolchain, &jobs, &scratch)?;
    let compiled = started.elapsed();
    let objects: Vec<PathBuf> = jobs.into_iter().map(|job| job.object).collect();
    let exe = program(entry);
    progress::phase(Phase::Link);
    let mut link = toolchain.link(&objects, &exe, &entry.folder.join("link.rsp"), &scratch)?;
    let output = link
        .output()
        .with_context(|| format!("running {}", toolchain.compiler().display()))?;
    check(&output, "linking the game")?;
    remove_folder(&scratch)?;
    let linked = started.elapsed();
    entry.finish()?;
    println!(
        "built in {:.1} s: discovered ({}) {:.1} s, translated {:.1} s, C written {:.1} s, {} \
         files compiled {:.1} s, linked {:.1} s",
        linked.as_secs_f64(),
        discovery.name(),
        analysed.as_secs_f64(),
        (translated - analysed).as_secs_f64(),
        (written - translated).as_secs_f64(),
        objects.len(),
        (compiled - written).as_secs_f64(),
        (linked - compiled).as_secs_f64(),
    );
    Ok(())
}

/// The RAM patches and flags of `code`, as the program embeds them.
fn extras(code: &CodePatches) -> Vec<Extra> {
    let ram = code.ram.iter().map(|patch| Extra::RamPatch {
        vblank: patch.when == When::Vblank,
        address: patch.address,
        bytes: patch.bytes.clone(),
    });
    let flags = code
        .flags
        .set()
        .into_iter()
        .map(|(name, value)| Extra::Flag {
            name: name.to_owned(),
            value: value.byte(),
        });
    ram.chain(flags).collect()
}

/// Writes the patch packs' C files into `sources` as `ag_patch_NNN.c`, each including
/// `ag_patch.h` and keeping its own name and lines for the compiler's messages, and returns
/// their paths.
fn write_patch_sources(code: &CodePatches, sources: &Path) -> Result<Vec<PathBuf>> {
    let mut files = Vec::with_capacity(code.sources.len());
    for (index, source) in code.sources.iter().enumerate() {
        let path = sources.join(format!("ag_patch_{index:03}.c"));
        let name = source.name.replace('\\', "/").replace('"', "'");
        let mut text = format!(
            "{}#include \"ag_patch.h\"\n#line 1 \"{name}\"\n",
            c_marker_line()
        )
        .into_bytes();
        text.extend(&source.text);
        fs::write(&path, text).with_context(|| format!("writing {}", path.display()))?;
        files.push(path);
    }
    Ok(files)
}

/// One file to compile.
#[derive(Debug)]
struct Job {
    source: PathBuf,
    object: PathBuf,
    /// Bytes in the source, to start the largest first.
    size: u64,
    stepped: bool,
}

/// The compile jobs for `sources` into `objects`, largest first so the last one to finish
/// is a small one.
fn compile_jobs(sources: &[PathBuf], objects: &Path) -> Result<Vec<Job>> {
    let mut jobs = Vec::with_capacity(sources.len());
    for source in sources {
        let stem = source
            .file_stem()
            .with_context(|| format!("{} has no file name", source.display()))?;
        let mut object = objects.join(stem);
        object.set_extension("o");
        let size = fs::metadata(source)
            .with_context(|| format!("reading {}", source.display()))?
            .len();
        jobs.push(Job {
            source: source.clone(),
            object,
            size,
            stepped: build::is_stepped_file(source),
        });
    }
    jobs.sort_by_key(|job| std::cmp::Reverse(job.size));
    Ok(jobs)
}

/// Compiles every job with Zig's local cache in `scratch`, one compiler process per core at a
/// time; stops starting new ones after the first failure.
fn compile_all(toolchain: &Toolchain, jobs: &[Job], scratch: &Path) -> Result<()> {
    let workers = thread::available_parallelism().map_or(1, |count| count.get());
    let next = AtomicUsize::new(0);
    let finished = AtomicUsize::new(0);
    progress::compiled(0, jobs.len());
    let failed = AtomicBool::new(false);
    let failure: Mutex<Option<anyhow::Error>> = Mutex::new(None);
    thread::scope(|scope| {
        for _ in 0..workers.min(jobs.len()) {
            scope.spawn(|| {
                while !failed.load(Ordering::Relaxed) {
                    let Some(job) = jobs.get(next.fetch_add(1, Ordering::Relaxed)) else {
                        break;
                    };
                    let result = toolchain
                        .compile(&job.source, &job.object, job.stepped, scratch)
                        .output()
                        .with_context(|| format!("running {}", toolchain.compiler().display()))
                        .and_then(|output| {
                            check(&output, &format!("compiling {}", job.source.display()))
                        });
                    match result {
                        Ok(()) => {
                            let done = finished.fetch_add(1, Ordering::Relaxed) + 1;
                            progress::compiled(done, jobs.len());
                        }
                        Err(error) => {
                            failed.store(true, Ordering::Relaxed);
                            failure
                                .lock()
                                .unwrap_or_else(std::sync::PoisonError::into_inner)
                                .get_or_insert(error);
                        }
                    }
                }
            });
        }
    });
    match failure
        .into_inner()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
    {
        Some(error) => Err(error),
        None => Ok(()),
    }
}

/// Fails with the tool's output unless it succeeded.
fn check(output: &Output, what: &str) -> Result<()> {
    if output.status.success() {
        return Ok(());
    }
    bail!(
        "{what} failed ({}):\n{}{}",
        output.status,
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

fn remove_folder(folder: &Path) -> Result<()> {
    match fs::remove_dir_all(folder) {
        Ok(()) => Ok(()),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error).with_context(|| format!("removing {}", folder.display())),
    }
}
